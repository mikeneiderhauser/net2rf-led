# Pre-build: gzip the web UI (web/index.html), the API page (web/api.html) and the API spec
# (docs/reference/openapi.yaml, stamped with the firmware version) into src/web_ui.h, so they can be edited as
# normal files.
import gzip
import os
import re
import subprocess

try:
    Import("env")  # noqa: F821
    project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:  # run directly: python3 tools/embed_ui.py
    env = None
    project_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def fw_version():
    """Same rule as tools/version.py: $FW_VERSION (CI), else `git describe`, else a dev fallback."""
    v = os.environ.get("FW_VERSION", "").strip()
    if not v:
        try:
            v = subprocess.check_output(["git", "describe", "--tags", "--always", "--dirty"], cwd=project_dir,
                                        stderr=subprocess.DEVNULL).decode().strip()
        except Exception:
            v = ""
    return v.lstrip("v") or "0.0.0-dev"


def read(*path):
    with open(os.path.join(project_dir, *path), "rb") as f:
        return f.read()


spec = re.sub(rb"(?m)^  version: .*$", b"  version: " + fw_version().encode(), read("docs", "reference", "openapi.yaml"),
              count=1)
parts = [
    ("INDEX_HTML_GZ", "web/index.html", read("web", "index.html")),
    ("API_HTML_GZ", "web/api.html", read("web", "api.html")),
    ("OPENAPI_YAML_GZ", "docs/reference/openapi.yaml", spec),
]

out = ("#pragma once\n"
       "// GENERATED by tools/embed_ui.py from " + ", ".join(p[1] for p in parts) + " - do not edit.\n"
       "#include <Arduino.h>\n")
for name, _, raw in parts:
    data = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + "," for i in range(0, len(data), 20)]
    out += (f"\nstatic const size_t {name}_LEN = {len(data)};\n"
            f"static const uint8_t {name}[] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n")
    print(f"{name}: {len(raw)} bytes -> {len(data)} bytes gzipped")

dst = os.path.join(project_dir, "src", "web_ui.h")
old = open(dst).read() if os.path.exists(dst) else None
if old != out:
    with open(dst, "w") as f:
        f.write(out)
